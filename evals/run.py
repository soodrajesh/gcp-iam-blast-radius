"""Cross-provider evaluation on the sample snapshots.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex,openai

Invariants (must hold on every run):
  posture_stable  posture equals the rules-only posture
  findings_intact every rule finding is unchanged
  fixes_verified  every shown fix was accepted by the simulator (re-checked here independently)
Reported: model notes kept/rejected, model patches accepted/rejected, cost, latency."""

import argparse
import asyncio
import json
import os
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "IAMBLAST_LLM":
        os.environ.setdefault(k, v)

from iamblast.llm import Budget, make_llm  # noqa: E402
from iamblast.orchestrator import analyze  # noqa: E402
from iamblast.remediate import verify  # noqa: E402
from iamblast.snapshot import load  # noqa: E402

SAMPLES = ROOT / "iamblast" / "samples"


async def main(providers, repeat, out):
    rows = []
    for name in sorted(p.stem for p in SAMPLES.glob("*.json")):
        doc = json.loads((SAMPLES / f"{name}.json").read_text())
        base = await analyze(doc, make_llm("none"))
        key = lambda a: Counter((f.rule, f.principal, f.severity, f.title) for f in a.findings)  # noqa: E731
        snap = load(doc)
        for prov in providers:
            for _ in range(repeat):
                a = await analyze(doc, make_llm(prov), budget=Budget())
                recheck = all(
                    verify(snap, v.patch, v.finding_id, v.origin, "").accepted for v in a.fixes
                )
                llm_fixes = [v for v in a.fixes if v.origin == "llm"]
                rows.append(
                    {
                        "snapshot": name,
                        "provider": f"{a.provider}/{a.model}",
                        "posture": a.posture,
                        "posture_stable": a.posture == base.posture,
                        "findings_intact": key(a) == key(base),
                        "fixes_verified": recheck,
                        "notes": sum(1 for f in a.findings if f.note),
                        "notes_rejected": sum(d["agent"] == "analyst" for d in a.dropped),
                        "llm_fixes": len(llm_fixes),
                        "patches_rejected": sum(d["agent"] == "planner" for d in a.dropped),
                        "degraded": len(a.degraded),
                        "cost": a.cost_usd,
                        "ms": a.duration_ms,
                    }
                )
                print(name, rows[-1]["provider"], a.posture, flush=True)
    ok = lambda r: r["posture_stable"] and r["findings_intact"] and r["fixes_verified"]  # noqa: E731
    bad = sum(not ok(r) for r in rows)
    L = [
        "# Evaluation results",
        "",
        "Generated by `evals/run.py`. Invariants must hold on every run.",
        "",
        "| snapshot | provider | posture | stable | findings intact | fixes verified | notes kept/rejected | model patches ok/rejected | degraded | cost | ms |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        c = lambda b: "✓" if b else "✗"  # noqa: E731
        L.append(
            f"| {r['snapshot']} | {r['provider']} | {r['posture']} | {c(r['posture_stable'])} | {c(r['findings_intact'])} | "
            f"{c(r['fixes_verified'])} | {r['notes']}/{r['notes_rejected']} | {r['llm_fixes']}/{r['patches_rejected']} | "
            f"{r['degraded']} | ${r['cost']:.4f} | {r['ms']} |"
        )
    by = {}
    for r in rows:
        by.setdefault(r["provider"], []).append(r)
    L += [
        "",
        "## Per provider",
        "",
        "| provider | runs | invariant violations | notes kept | notes rejected | model patches accepted | model patches rejected | cost | median ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p, rs in by.items():
        L.append(
            f"| {p} | {len(rs)} | {sum(not ok(x) for x in rs)} | {sum(x['notes'] for x in rs)} | {sum(x['notes_rejected'] for x in rs)} | "
            f"{sum(x['llm_fixes'] for x in rs)} | {sum(x['patches_rejected'] for x in rs)} | ${sum(x['cost'] for x in rs):.4f} | {int(statistics.median(x['ms'] for x in rs))} |"
        )
    out.write_text("\n".join(L) + "\n")
    print(f"\nwrote {out}; invariant violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--repeat", type=int, default=1)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.providers.split(","), a.repeat, a.out)))
